def main(argv):
    steps = argv or ALL_STEPS
    expanded = []
    for s in steps:
        if s == "models":
            expanded += MODEL_STEPS
        elif s == "all":
            expanded += ALL_STEPS
        else:
            expanded.append(s)
    t = time.time()
    for s in expanded:
        name, _, arg = s.partition(":")
        step(name, arg or None)
    # keep the Caltrop alias used by Weapons/Deployables
    src = os.path.join(C.MODELS, "Missiles", "Caltrops.fbx")
    if os.path.exists(src):
        import shutil
        shutil.copyfile(src, os.path.join(C.MODELS, "Missiles", "Caltrop.fbx"))
    print("== all done in %.0fs" % (time.time() - t))


if __name__ == "__main__":
    main(sys.argv[1:])
