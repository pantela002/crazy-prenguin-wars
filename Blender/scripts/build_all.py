"""Crazy Penguin Wars art pipeline: builds every model, texture and icon procedurally with Blender (bpy module).

Usage (from the repo root):
    python3 Blender/scripts/build_all.py                 # everything (models, textures, icons, docs, verify)
    python3 Blender/scripts/build_all.py models          # all models only
    python3 Blender/scripts/build_all.py penguin clothes # some steps
    python3 Blender/scripts/build_all.py icons:Weapons,Clothes   # some icon sections
Steps: penguin clothes weapons missiles props env textures icons docs verify  (models = the first six)
Env: CPW_SAMPLES=32 (Cycles samples for icons).
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy  # noqa: E402,F401

import common as C  # noqa: E402

MODEL_STEPS = ["penguin", "clothes", "weapons", "missiles", "props", "env"]
ALL_STEPS = MODEL_STEPS + ["textures", "icons", "docs", "verify"]


def step(name, arg=None):
    t = time.time()
    if name == "penguin":
        import penguin
        penguin.run()
    elif name == "clothes":
        import clothes
        clothes.run()
    elif name == "weapons":
        import weapons
        weapons.run()
    elif name == "missiles":
        import missiles
        missiles.run()
    elif name == "props":
        import props
        props.run()
    elif name == "env":
        import env
        env.run()
    elif name == "textures":
        import textures
        textures.run()
    elif name == "icons":
        import icons
        icons.run(arg.split(",") if arg else None)
    elif name == "docs":
        write_docs()
    elif name == "verify":
        verify()
    else:
        raise SystemExit("unknown step " + name)
    print("== %s done in %.1fs" % (name, time.time() - t), flush=True)


def verify():
    """Re-import the penguin FBX and check size and orientation in Unity terms."""
    import verify_fbx
    lo, hi, parts = verify_fbx.verify(os.path.join(C.MODELS, "Penguin", "Penguin.fbx"), verbose=False)
    size = hi - lo
    beak = (parts["Beak"][0] + parts["Beak"][1]) / 2
    belly = (parts["Belly"][0] + parts["Belly"][1]) / 2
    ok = abs(size.y - 2.6) < 0.2 and lo.y > -0.1 and beak.x > 0.2 and belly.z < -0.1
    print("[verify] Penguin.fbx Unity size (%.2f, %.2f, %.2f), feet y=%.2f, beak x=%.2f (+X = facing right), belly z=%.2f "
          "(-Z = towards camera): %s" % (size.x, size.y, size.z, lo.y, beak.x, belly.z, "OK" if ok else "FAILED"))
    lo, hi, parts = verify_fbx.verify(os.path.join(C.MODELS, "Weapons", "MiniBazooka.fbx"), verbose=False)
    mz = parts.get("Muzzle")
    print("[verify] MiniBazooka.fbx x range %.2f..%.2f, Muzzle at x=%.2f: %s" % (
        lo.x, hi.x, mz[0].x if mz else float("nan"), "OK" if mz and mz[0].x > 0.4 else "FAILED"))
    for wid in ("HeatSeeker", "GreyGoo", "ChocoCannon"):
        lo, hi, parts = verify_fbx.verify(os.path.join(C.MODELS, "Weapons", wid + ".fbx"), verbose=False)
        mz = parts.get("Muzzle")
        good = bool(mz) and mz[0].x > 0.3 and abs(mz[0].x - hi.x) < 0.25
        print("[verify] %s.fbx x range %.2f..%.2f, Muzzle at x=%.2f: %s" % (
            wid, lo.x, hi.x, mz[0].x if mz else float("nan"), "OK" if good else "FAILED"))
        ok = ok and good
    if not ok:
        raise SystemExit(1)


def _listing(folder, ext):
    p = os.path.join(C.RES, folder)
    if not os.path.isdir(p):
        return []
    return sorted(os.path.splitext(f)[0] for f in os.listdir(p) if f.endswith(ext))


